// EconsPassQuestionCard/EconsPassRoom (like the Comm Skills room) index the
// correct option by position rather than matching the answer string, so this
// adapts the bank's {section, answer: string} shape into that {topic,
// correctIndex} shape once, up front.
export interface EconsPassIndexedQuestion {
  id: string;
  topic: EconsPassSection;
  code?: string;
  table?: EconsPassTable;
  chartId?: string;
  question: string;
  options: string[];
  correctIndex: number;
  explanation: string;
  source?: EconsPassSource;
  sourceIssue?: string;
}

export function toIndexedQuestions(bank: EconsPassQuestion[]): EconsPassIndexedQuestion[] {
  return bank
    .filter((q): q is EconsPassQuestion & { options: string[] } => Array.isArray(q.options))
    .map((q) => {
      const correctIndex = q.options.indexOf(q.answer);
      return {
        id: q.id,
        topic: q.section,
        code: q.code,
        table: q.table,
        chartId: q.chartId,
        question: q.question,
        options: q.options,
        correctIndex: correctIndex === -1 ? 0 : correctIndex,
        explanation: q.explanation,
        source: q.source,
        sourceIssue: q.sourceIssue,
      };
    });
}

